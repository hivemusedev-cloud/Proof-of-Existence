//! poe-crypto — the Proof of Existence crypto carriers (BUILD_FLOW Step 2).
//!
//! The kernel speaks of marks, tickets and keys abstractly; this crate is
//! where they become cryptography. Everything here is replaceable under the
//! kernel law — the kernel never sees a hash function — but within this
//! crate the choices are fixed and test-vectored:
//!
//! * [`hash`] — `H`, the seed-exact hash: SHAKE256 under the domain tag
//!   `b"PoE/" + tag`, length-framed parts, 512-bit output, byte-for-byte the
//!   Compute Seed's `physos_fabric/hashing.py` construction, plus its Merkle
//!   commitments. Test vectors are generated by the Python original.
//! * [`tickets`] — hash-chain proposal tickets: commit the chain tip, reveal
//!   one link per round, ticket below `16/A` of its range wins (~16 expected
//!   proposers per round at `A` active machines).
//! * [`xmss`] — XMSS-style one-time vote keys (WOTS+ leaves under a Merkle
//!   tree) whose leaf state is persisted *before* a signature is released,
//!   so a crash can burn a leaf but can never reuse one.
//! * [`pq`] — ML-DSA-87 signatures and ML-KEM-1024 key encapsulation over
//!   the audited `fips204`/`fips203` implementations of FIPS 204/203.

pub mod hash;
pub mod pq;
pub mod tickets;
pub mod xmss;
